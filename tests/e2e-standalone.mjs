import { chromium } from 'playwright';
const b = await chromium.launch(); const ctx = await b.newContext(); const p = await ctx.newPage();
const errs = []; p.on('pageerror', e => errs.push(e.message));
await p.goto('http://localhost:4500/');
await p.evaluate(() => localStorage.setItem('xpos_autoprint', '0'));
await p.click('button:has-text("Sign in")');
await p.waitForSelector('text=Local-only mode', { timeout: 15000 });
await ctx.setOffline(true);
await p.click('a:has-text("POS Counter")');
for (const d of '1234') await p.click(`button:text-is("${d}")`);
const s = p.locator('input[placeholder*="scan barcode"]'); await s.fill('NM-1L'); await s.press('Enter');
await p.click('button:has-text("Pay Rs")'); await p.click('button:has-text("Complete sale")');
await p.waitForSelector('text=/Sale .* saved/');
await p.reload(); await p.waitForSelector('text=Local-only mode', { timeout: 10000 });
await p.click('a:has-text("Accounts")'); await p.click('main button:has-text("Trial balance")');
const bal = (await p.locator('main').innerText()).includes('Balanced');
await p.click('a:has-text("Sales & Returns")'); await p.waitForTimeout(500);
const sale = (await p.locator('main').innerText()).includes('290');
console.log({ offlineReloadAndSale: sale, trialBalanceBalanced: bal, errors: errs });
await b.close();
